"""Darwin Genome — Attack representation, mutation operators, and scenario compilation."""

from __future__ import annotations

import copy
import hashlib
import json
import random
from dataclasses import dataclass, field
from typing import Any

from app.darwin.personas import get_active_personas, get_persona


@dataclass
class Genome:
    persona: str
    strategy: str
    steps: list[dict[str, Any]]
    seed: int = 42
    generation: int = 0
    parent_ids: list[str] = field(default_factory=list)
    id: str = ""
    metadata: dict[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if not self.id:
            self.id = self.compute_hash()

    def compute_hash(self) -> str:
        raw = f"{self.persona}:{self.strategy}:{json.dumps(self.steps, sort_keys=True)}"
        return hashlib.sha256(raw.encode()).hexdigest()[:12]

    def to_dict(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "persona": self.persona,
            "strategy": self.strategy,
            "steps": copy.deepcopy(self.steps),
            "seed": self.seed,
            "generation": self.generation,
            "parent_ids": list(self.parent_ids),
            "metadata": copy.deepcopy(self.metadata),
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> Genome:
        return cls(
            persona=data["persona"],
            strategy=data.get("strategy", "attack"),
            steps=data.get("steps", []),
            seed=data.get("seed", 42),
            generation=data.get("generation", 0),
            parent_ids=data.get("parent_ids", []),
            id=data.get("id", ""),
            metadata=data.get("metadata", {}),
        )

    def compile_to_scenario(self) -> dict[str, Any]:
        """Emits the existing scenario JSON format compatible with scenario_runner.py."""
        p = get_persona(self.persona)

        # Build deterministic baseline checks
        checks: list[dict[str, Any]] = [
            {"type": "reply_nonempty", "turn": -1},
        ]

        # Dictation-specific checks if persona is dictation-focused
        if p.is_dictation_focused:
            if self.persona == "self_corrector":
                checks.append({
                    "type": "reply_not_contains",
                    "any_of": ["no wait", "scratch that", "actually wait"],
                    "turn": -1,
                })
            elif self.persona == "filler_heavy_rambler":
                checks.append({
                    "type": "reply_not_contains",
                    "any_of": ["um", "uh", "you know"],
                    "turn": -1,
                })

        return {
            "name": f"Darwin [{p.name}] {self.strategy[:35]}",
            "category": self.persona,
            "description": f"Automated adversarial scenario generated by Darwin (Gen {self.generation}, {self.strategy})",
            "steps": copy.deepcopy(self.steps),
            "expected_behavior": (
                f"Agent must withstand attack from {p.name}: correctly process user intent, "
                "handle interruptions/failures gracefully, and maintain state without crashing."
            ),
            "latency_budget_ms": 6000,
            "checks": checks,
        }


# --- Factory & Initial Population ---

def create_random_genome(
    persona_id: str,
    seed: int,
    generation: int = 0,
    rng: random.Random | None = None,
) -> Genome:
    r = rng or random.Random(seed)
    persona = get_persona(persona_id)
    strategy = r.choice(persona.strategies) if persona.strategies else "adversarial probe"

    # Start with 2 to 4 turns from the persona heuristic bank or generated prompts
    num_steps = r.randint(2, 4)
    steps: list[dict[str, Any]] = []

    bank = persona.heuristic_bank
    for _ in range(num_steps):
        content = r.choice(bank) if bank else "Hello, I need help."
        # Occasionally inject interruption on creation if persona warrants it
        if persona.id == "impatient_interrupter" and len(steps) > 0 and r.random() < 0.4:
            steps.append({"type": "interrupt", "content": content})
        else:
            steps.append({"type": "user_message", "content": content})

    return Genome(
        persona=persona_id,
        strategy=strategy,
        steps=steps,
        seed=seed,
        generation=generation,
        parent_ids=[],
    )


# --- Mutation Operators ---

def swap_persona(genome: Genome, rng: random.Random) -> Genome:
    """Change persona, keep the strategy and adapt."""
    available = [p.id for p in get_active_personas() if p.id != genome.persona]
    if not available:
        return copy.deepcopy(genome)
    new_persona = rng.choice(available)
    p_def = get_persona(new_persona)

    new_genome = copy.deepcopy(genome)
    new_genome.persona = new_persona
    new_genome.parent_ids = [genome.id]

    # Optionally replace a step with new persona content
    if new_genome.steps and p_def.heuristic_bank:
        idx = rng.randint(0, len(new_genome.steps) - 1)
        step_type = new_genome.steps[idx].get("type", "user_message")
        new_genome.steps[idx] = {"type": step_type, "content": rng.choice(p_def.heuristic_bank)}

    new_genome.id = new_genome.compute_hash()
    return new_genome


def inject_interruption(genome: Genome, rng: random.Random) -> Genome:
    """Insert an interrupt step at a random turn."""
    new_genome = copy.deepcopy(genome)
    p_def = get_persona(new_genome.persona)
    content = rng.choice(p_def.heuristic_bank) if p_def.heuristic_bank else "Wait, stop right there!"

    insert_idx = rng.randint(1, max(1, len(new_genome.steps)))
    new_genome.steps.insert(insert_idx, {"type": "interrupt", "content": content})
    new_genome.parent_ids = [genome.id]
    new_genome.id = new_genome.compute_hash()
    return new_genome


def inject_api_failure(genome: Genome, rng: random.Random) -> Genome:
    """Insert a tool_failure step mid-conversation to stress error recovery."""
    new_genome = copy.deepcopy(genome)
    insert_idx = rng.randint(0, max(0, len(new_genome.steps) - 1))
    new_genome.steps.insert(insert_idx, {"type": "tool_failure", "content": ""})
    new_genome.parent_ids = [genome.id]
    new_genome.id = new_genome.compute_hash()
    return new_genome


def extend_conversation(genome: Genome, rng: random.Random) -> Genome:
    """Add N more turns (1-2) to stress context retention."""
    new_genome = copy.deepcopy(genome)
    p_def = get_persona(new_genome.persona)
    extra_count = rng.randint(1, 2)

    for _ in range(extra_count):
        content = rng.choice(p_def.heuristic_bank) if p_def.heuristic_bank else "What did I ask previously?"
        new_genome.steps.append({"type": "user_message", "content": content})

    new_genome.parent_ids = [genome.id]
    new_genome.id = new_genome.compute_hash()
    return new_genome


def crossover(parent_a: Genome, parent_b: Genome, rng: random.Random | None = None) -> Genome:
    """Splices the first half of parent A's steps onto the second half of parent B."""
    steps_a = parent_a.steps
    steps_b = parent_b.steps

    split_a = max(1, len(steps_a) // 2)
    split_b = max(1, len(steps_b) // 2)

    combined_steps = copy.deepcopy(steps_a[:split_a]) + copy.deepcopy(steps_b[split_b:])
    if not combined_steps:
        combined_steps = copy.deepcopy(steps_a)

    # Inherit persona and strategy from parent A
    child = Genome(
        persona=parent_a.persona,
        strategy=parent_a.strategy,
        steps=combined_steps,
        seed=parent_a.seed,
        generation=max(parent_a.generation, parent_b.generation) + 1,
        parent_ids=[parent_a.id, parent_b.id],
    )
    return child


MUTATION_OPERATORS = [
    swap_persona,
    inject_interruption,
    inject_api_failure,
    extend_conversation,
]


def mutate(genome: Genome, rng: random.Random) -> Genome:
    """Select a random mutation operator and apply it."""
    op = rng.choice(MUTATION_OPERATORS)
    mutated = op(genome, rng)
    mutated.generation = genome.generation + 1
    mutated.id = mutated.compute_hash()
    return mutated
